// The catalog entry a live validation feed runs (NAN-3490): the shipped
// okta_system_log spec, renamed, with its allowlist pinned to the ONE mock
// host. Everything else (windows, lag, lookback, paging, rate limits, VRL,
// source_type) is byte-for-byte the shipped spec, so the run exercises what a
// real Okta feed runs.
//
// The shipped spec only allows Okta's own domains, so it cannot reach a mock.
// The copy does not widen that to a suffix: an exact host means a feed made
// from it can only ever talk to the mock.
//
//   deno run --allow-read testing/okta-mock-public/catalog.ts --host <mock host> [--spec-out <path>]
//
// prints the `marketplace_catalog.config` JSON nano's feed create reads
// (`runtime`, `connector_spec`, `connector_spec_sha256`). This file is under
// testing/, so repo sync never installs it; the operator inserts the entry for
// the validation window only.

export const MOCK_CONNECTOR = "okta_system_log_mock";

const SHIPPED = new URL(
  "../../integrations/okta_system_log/connector.yaml",
  import.meta.url,
);

const NAME_LINE = "name: okta_system_log\n";
const ALLOW_LINES = '  - host: "{{config.OKTA_DOMAIN}}"\n' +
  '    host_suffixes: [".okta.com", ".oktapreview.com", ".okta-emea.com", ".okta-gov.com", ".okta.mil"]\n';

const OKTA_SUFFIXES = [
  ".okta.com",
  ".oktapreview.com",
  ".okta-emea.com",
  ".okta-gov.com",
  ".okta.mil",
];

/** A public DNS name: lowercase labels, at least two, no IP literal, not Okta's. */
export function checkHost(host: string): string {
  const h = host.trim().toLowerCase();
  const label = /^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/;
  const labels = h.split(".");
  if (
    h.length > 253 || labels.length < 2 ||
    !labels.every((l) => label.test(l)) || /^\d+$/.test(labels.at(-1)!)
  ) {
    throw new Error(`--host ${JSON.stringify(host)} is not a public host name`);
  }
  if (OKTA_SUFFIXES.some((s) => `.${h}`.endsWith(s))) {
    throw new Error(`--host ${h} is an Okta domain, not the mock`);
  }
  return h;
}

function replaceOnce(text: string, find: string, by: string): string {
  const at = text.indexOf(find);
  if (at < 0 || text.indexOf(find, at + 1) >= 0) {
    throw new Error(
      `shipped okta_system_log spec changed: expected exactly one ${
        JSON.stringify(find)
      }; update catalog.ts`,
    );
  }
  return text.slice(0, at) + by + text.slice(at + find.length);
}

export function mockSpec(shipped: string, host: string): string {
  const h = checkHost(host);
  let s = replaceOnce(shipped, NAME_LINE, `name: ${MOCK_CONNECTOR}\n`);
  s = replaceOnce(s, ALLOW_LINES, `  - host: "${h}"\n`);
  return `# LIVE-VALIDATION COPY of okta_system_log, pinned to the public mock ${h}.\n` +
    `# Generated by testing/okta-mock-public/catalog.ts; do not ship.\n` + s;
}

export async function sha256Hex(text: string): Promise<string> {
  const d = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(text),
  );
  return Array.from(new Uint8Array(d), (b) => b.toString(16).padStart(2, "0"))
    .join("");
}

export async function catalogConfig(
  host: string,
  shipped?: string,
): Promise<Record<string, string>> {
  const spec = mockSpec(shipped ?? await Deno.readTextFile(SHIPPED), host);
  return {
    runtime: "connector",
    connector_spec: spec,
    connector_spec_sha256: await sha256Hex(spec),
  };
}

if (import.meta.main) {
  const args = [...Deno.args];
  const flag = (name: string) => {
    const i = args.indexOf(name);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const host = flag("--host");
  if (!host) {
    console.error("usage: catalog.ts --host <mock host> [--spec-out <path>]");
    Deno.exit(2);
  }
  const cfg = await catalogConfig(host);
  const out = flag("--spec-out");
  if (out) await Deno.writeTextFile(out, cfg.connector_spec);
  console.log(JSON.stringify(cfg));
}
